/** The mark, hidden from assistive technology; `currentColor` draws it in the text's colour. */
export function drawMark(doc: Document, colour: 'brand' | 'currentColor'): SVGSVGElement {
  const svg = doc.createElementNS(SVG, 'svg');
  svg.setAttribute('viewBox', '0 0 72 39');
  svg.setAttribute('class', 'mark');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  for (const [fill, outline] of BANDS) {
    const band = doc.createElementNS(SVG, 'path');
    band.setAttribute('fill', colour === 'brand' ? fill : 'currentColor');
    // One colour shows the seams between bands unless each band also strokes its outline.
    if (colour === 'currentColor') band.setAttribute('stroke', 'currentColor');
    band.setAttribute('d', outline);
    svg.append(band);
  }
  return svg;
}
